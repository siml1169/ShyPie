#!/usr/bin/env node
/**
 * Vendor `packages/pii-core/index.js` into `vendor/pii-core.js`.
 *
 * A DSH bundle is a self-contained package: it must load its redaction module
 * from its own directory, not by reaching into a sibling workspace package at
 * runtime. This script is the one honest copy step:
 *
 *   node scripts/vendor-core.mjs          # copy (fails if the source is absent)
 *   node scripts/vendor-core.mjs --check  # verify vendor/pii-core.js is current
 *
 * The copy is byte-for-byte plus a provenance header. It refuses a source that
 * imports a Node builtin, because docs/interface-contract.md requires the core to stay plain
 * ES modules (Magpie's moejs middleware loads the same code).
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, relative } from 'node:path'
import { fileURLToPath } from 'node:url'

const HERE = dirname(fileURLToPath(import.meta.url))
const PLUGIN_ROOT = join(HERE, '..')
const WORKFLOW_ROOT = join(PLUGIN_ROOT, '..', '..')
const SOURCE = join(WORKFLOW_ROOT, 'packages', 'pii-core', 'index.js')
const TARGET = join(PLUGIN_ROOT, 'vendor', 'pii-core.js')

const HEADER = `// VENDORED COPY — do not edit.
// Source: packages/pii-core/index.js
// Generated by: plugins/dsh-privacy-gate/scripts/vendor-core.mjs
`

const check = process.argv.includes('--check')

if (!existsSync(SOURCE)) {
  console.error(`vendor-core: missing source ${relative(WORKFLOW_ROOT, SOURCE)}`)
  console.error('vendor-core: pii-core has not been written yet; run this again once it exists')
  process.exit(1)
}

const source = readFileSync(SOURCE, 'utf8')
if (/from\s+['"]node:/.test(source) || /require\(\s*['"]node:/.test(source)) {
  console.error('vendor-core: refusing to vendor a core that imports a Node builtin (docs/interface-contract.md: index.js must be plain ESM)')
  process.exit(1)
}

const content = `${HEADER}${source}`

if (check) {
  if (!existsSync(TARGET)) {
    console.error(`vendor-core: ${relative(PLUGIN_ROOT, TARGET)} is missing; run scripts/vendor-core.mjs`)
    process.exit(1)
  }
  if (readFileSync(TARGET, 'utf8') !== content) {
    console.error(`vendor-core: ${relative(PLUGIN_ROOT, TARGET)} is stale; run scripts/vendor-core.mjs`)
    process.exit(1)
  }
  console.log('vendor-core: up to date')
  process.exit(0)
}

mkdirSync(dirname(TARGET), { recursive: true })
writeFileSync(TARGET, content, 'utf8')
console.log(`vendor-core: wrote ${relative(PLUGIN_ROOT, TARGET)} (${source.length} bytes)`)
